#!/usr/bin/env node
'use strict';
// OzarLand Production Guide: build.
//
//   node scripts/build.cjs                 validate, render every memo to dist/, regenerate pages and catalog
//   node scripts/build.cjs --only <slug>   render one memo (pages and catalog are still regenerated)
//   node scripts/build.cjs --validate      validate content and runbook links only, render nothing
//   node scripts/build.cjs --scale 2       export at 2160 x 2700 instead of 1080 x 1350
//   node scripts/build.cjs --runbooks DIR  use this checkout of openstack-vm-runbooks for the link check
//   node scripts/build.cjs --offline       skip the runbook check when no checkout is available
//
// Sources: categories/<category>/<slug>.yml (content), templates/ (presentation).
// Outputs: dist/*.png, categories/<category>/<slug>.md, README.md catalog, LINKEDIN.md.

const fs = require('fs');
const path = require('path');
const { ROOT, loadMemos, validateMemo, validateCollection, fileBase } = require('./lib/content.cjs');
const { REPO, BLOB, findCheckout, checkRunbooks } = require('./lib/runbooks.cjs');
const { renderMemo, plain, CATEGORIES, CAUTION } = require('../templates/memo.cjs');

const args = process.argv.slice(2);
const flag = (n) => args.includes(n);
const opt = (n) => (args.includes(n) ? args[args.indexOf(n) + 1] : undefined);

const DIST = path.join(ROOT, 'dist');
const HTML = path.join(ROOT, '.cache', 'html');
const GUIDE = 'https://github.com/OzarLand/production-guide';
const GENERATED = (src) => `<!-- Generated by scripts/build.cjs from ${src}. Do not edit: change the source and rebuild. -->`;

function fail(errors) {
  console.error(`\n${errors.length} problem(s):\n` + errors.map((e) => `  - ${e}`).join('\n'));
  process.exit(1);
}

// ---------- Generated Markdown ----------

const mdText = (s) => String(s).replace(/\*\*([^*]+)\*\*/g, '$1');

function memoPage(m) {
  const img = `../../dist/${fileBase(m)}.png`;
  const rbs = m._runbooks && m._runbooks.length ? m._runbooks : [{ path: m.runbook.path, url: BLOB + m.runbook.path }];
  const li = m.linkedin;
  const tags = li.hashtags.map((t) => `#${t}`).join(' ');
  const out = [
    `[← Production Guide](../../README.md#catalog) · ${CATEGORIES[m.category]}`,
    '',
    GENERATED(`${m._slug}.yml`),
    '',
    `# ${m.id} · ${mdText(m.title)}`,
    '',
    `<img src="${img}" alt="${plain(m.title)} Operational lesson: ${plain(m.lesson)}" width="540">`,
    '',
    `> **Operational lesson.** ${mdText(m.lesson)}`,
    '',
    '## The memo as text',
    '',
    `**Situation.** ${mdText(m.situation)}`,
    '',
    '**First checks** (read-only):',
    '',
    ...m.checks.map((c, i) => `${i + 1}. **${mdText(c.label)}**${c.hint ? `: \`${c.hint}\`` : ''}`),
    '',
    '**Think before acting:**',
    '',
    ...m.caution.map((c) => `- ${c.level === 'destructive' ? '🛑' : c.level === 'state-changing' ? '⚠️' : c.level === 'avoid' ? '⛔' : 'ℹ️'} **${CAUTION[c.level].tag}** ${mdText(c.text)}`),
    '',
    '## Go deeper',
    '',
    'This memo is a memory aid. The procedure, with every command, its risk warning and its limits, is in the runbook:',
    '',
    ...rbs.map((r) => `- [${r.title || r.path}](${r.url})${r.status ? ` · \`${r.status}\`${r.releases && r.releases.length ? ` on ${r.releases.join(', ')}` : ''}${r.risk ? ` · highest risk in the page: ${r.risk}` : ''}` : ''}`),
    '',
    `**Where this holds.** ${mdText(m.scope)}`,
    '',
    '## LinkedIn kit',
    '',
    `- **Image:** [\`dist/${fileBase(m)}.png\`](${img}) (1080 × 1350)`,
    `- **Post title:** ${li.title}`,
    '',
    '```text',
    li.caption.trim(),
    '',
    `Runbook: ${rbs[0].url}`,
    `More memos: ${GUIDE}`,
    '',
    tags,
    '```',
    '',
    '---',
    '',
    `*Source: [\`${m._slug}.yml\`](${m._slug}.yml). Found an error, or does your platform behave differently? [Open an issue](${GUIDE}/issues/new) or see [CONTRIBUTING](../../CONTRIBUTING.md).*`,
    '',
  ];
  return out.join('\n');
}

function catalog(memos) {
  const out = [];
  for (const [cat, name] of Object.entries(CATEGORIES)) {
    const list = memos.filter((m) => m.category === cat);
    if (!list.length) continue;
    out.push(`### ${name}`, '', '| | Memo | Operational lesson | Runbook |', '|---|---|---|---|');
    for (const m of list) {
      const page = `categories/${cat}/${m._slug}.md`;
      out.push(
        `| <a href="${page}"><img src="dist/${fileBase(m)}.png" alt="${plain(m.title)}" width="150"></a> ` +
          `| **${m.id}**<br>[${mdText(m.title)}](${page}) ` +
          `| ${mdText(m.lesson)} ` +
          `| [${m.runbook.path.split('/')[0]}/…](${BLOB + m.runbook.path})<br>\`${m.runbook.status}\` |`
      );
    }
    out.push('');
  }
  return out.join('\n');
}

function categoryIndex(cat, memos) {
  const list = memos.filter((m) => m.category === cat);
  return [
    '[← Production Guide](../../README.md#catalog)',
    '',
    GENERATED('the memo sources in this folder'),
    '',
    `# ${CATEGORIES[cat]}`,
    '',
    ...list.map((m) => `- **${m.id}** [${mdText(m.title)}](${m._slug}.md): ${mdText(m.lesson)}`),
    '',
  ].join('\n');
}

function linkedinKit(memos) {
  const out = [
    '[← Production Guide](README.md)',
    '',
    GENERATED('the linkedin block of every memo source'),
    '',
    '# LinkedIn publishing kit',
    '',
    'One post per memo: the image, a title, a caption and hashtags, ready to paste. The suggested order is the memo',
    'number. Each caption ends with the link to its runbook and to this repository.',
    '',
    '| # | Post title | Image | Page |',
    '|---|---|---|---|',
    ...memos.map((m) => `| ${m.id} | ${m.linkedin.title} | [\`${fileBase(m)}.png\`](dist/${fileBase(m)}.png) | [page](categories/${m.category}/${m._slug}.md#linkedin-kit) |`),
    '',
  ];
  for (const m of memos) {
    out.push(
      `## ${m.id} · ${m.linkedin.title}`,
      '',
      `Image: [\`dist/${fileBase(m)}.png\`](dist/${fileBase(m)}.png)`,
      '',
      '```text',
      m.linkedin.caption.trim(),
      '',
      `Runbook: ${BLOB + m.runbook.path}`,
      `More memos: ${GUIDE}`,
      '',
      m.linkedin.hashtags.map((t) => `#${t}`).join(' '),
      '```',
      ''
    );
  }
  return out.join('\n');
}

function replaceBlock(file, name, content) {
  const p = path.join(ROOT, file);
  if (!fs.existsSync(p)) return;
  const t = fs.readFileSync(p, 'utf8');
  const re = new RegExp(`(<!-- ${name}:start -->)[\\s\\S]*?(<!-- ${name}:end -->)`);
  if (!re.test(t)) return;
  fs.writeFileSync(p, t.replace(re, `$1\n${content}\n$2`));
}

// Every relative link and image in the Markdown of the repository must point at a file that exists.
function checkLocalLinks() {
  const errors = [];
  const walk = (dir) =>
    fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
      if (['node_modules', '.git', '.cache'].includes(e.name)) return [];
      const p = path.join(dir, e.name);
      return e.isDirectory() ? walk(p) : e.name.endsWith('.md') ? [p] : [];
    });
  for (const file of walk(ROOT)) {
    const text = fs.readFileSync(file, 'utf8').replace(/```[\s\S]*?```/g, '');
    const targets = [...text.matchAll(/\]\(([^)\s]+)\)/g), ...text.matchAll(/(?:src|href)="([^"]+)"/g)].map((m) => m[1]);
    for (const t of targets) {
      if (/^(https?:|mailto:|#)/.test(t)) continue;
      const target = path.resolve(path.dirname(file), decodeURI(t.split('#')[0]));
      if (!fs.existsSync(target)) errors.push(`${path.relative(ROOT, file)}: link to "${t}" points at nothing`);
    }
  }
  return errors;
}

// ---------- Rendering ----------

// Runs in the page: reports anything that does not fit its box. The template never shrinks text to fit.
function measure() {
  const problems = [];
  const over = (el, name) => {
    if (el.scrollHeight > el.clientHeight + 1) problems.push(`${name} overflows by ${el.scrollHeight - el.clientHeight}px vertically`);
    if (el.scrollWidth > el.clientWidth + 1) problems.push(`${name} overflows by ${el.scrollWidth - el.clientWidth}px horizontally`);
  };
  const body = document.querySelector('.body');
  const memo = document.querySelector('.memo');
  if (body.scrollHeight > body.clientHeight + 1) problems.push(`the content is ${body.scrollHeight - body.clientHeight}px too tall: shorten the situation, the diagram or the cautions`);
  if (memo.scrollHeight > memo.clientHeight + 1) problems.push('the memo is taller than the canvas');
  // .node is left out: its status badge sits outside the box on purpose. Its text is checked instead.
  document.querySelectorAll('.node-label, .node-sub, .col, .br-see, .br-means, .checks li').forEach((el, i) => over(el, `${el.className.split(' ')[0]} #${i + 1}`));
  document.querySelectorAll('.c-hint').forEach((el, i) => {
    if (el.getBoundingClientRect().height > 56) problems.push(`the hint of check ${i + 1} takes more than two lines`);
  });
  if (document.querySelector('.lesson-text').getBoundingClientRect().height > 90) problems.push('the lesson takes more than two lines');
  if (document.querySelector('.title').getBoundingClientRect().height > 150) problems.push('the title takes more than two lines');
  if (document.querySelector('.situation').getBoundingClientRect().height > 108) problems.push('the situation takes more than three lines');
  // Free height left in the body once every section has its natural size.
  let used = 0;
  for (const el of body.children) {
    const cs = getComputedStyle(el);
    used += el.getBoundingClientRect().height + parseFloat(cs.marginTop) + parseFloat(cs.marginBottom);
  }
  const cs = getComputedStyle(body);
  const free = Math.round(body.clientHeight - parseFloat(cs.paddingTop) - parseFloat(cs.paddingBottom) - used);
  return { problems, free };
}

async function render(memos, scale) {
  const { chromium } = require('playwright');
  fs.mkdirSync(DIST, { recursive: true });
  fs.mkdirSync(HTML, { recursive: true });
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1080, height: 1350 }, deviceScaleFactor: scale });
  const errors = [];
  for (const m of memos) {
    const html = path.join(HTML, `${fileBase(m)}.html`);
    fs.writeFileSync(html, renderMemo(m));
    await page.goto(`file://${html}`);
    await page.evaluate(() => document.fonts.ready);
    const r = await page.evaluate(measure);
    r.problems.forEach((p) => errors.push(`${m._file}: ${p}`));
    const out = path.join(DIST, `${fileBase(m)}${scale === 1 ? '' : `@${scale}x`}.png`);
    await page.locator('.memo').screenshot({ path: out });
    console.log(`  ${m.id}  ${path.relative(ROOT, out)}  (${r.free}px free${r.free > 110 ? ', sparse' : ''})`);
  }
  await browser.close();
  return errors;
}

async function contactSheet(memos) {
  const { chromium } = require('playwright');
  const cols = 5;
  const cells = memos.map((m) => `<img src="../../dist/${fileBase(m)}.png">`).join('');
  const html = path.join(HTML, 'contact-sheet.html');
  fs.writeFileSync(
    html,
    `<!doctype html><meta charset="utf-8"><style>body{margin:0;background:#0e1a2b}main{display:grid;grid-template-columns:repeat(${cols},1fr);gap:18px;padding:18px;width:1800px;box-sizing:border-box}img{width:100%;display:block;border-radius:6px}</style><main>${cells}</main>`
  );
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1800, height: 1000 } });
  await page.goto(`file://${html}`);
  await page.locator('main').screenshot({ path: path.join(DIST, 'contact-sheet.png') });
  await browser.close();
}

// ---------- Main ----------

(async () => {
  const memos = loadMemos();
  console.log(`${memos.length} memo(s) found`);

  let errors = [...validateCollection(memos), ...memos.flatMap((m) => validateMemo(m))];
  if (errors.length) fail(errors);

  const runbooks = findCheckout(opt('--runbooks'));
  if (runbooks) {
    errors = checkRunbooks(memos, runbooks);
    if (errors.length) fail(errors);
    console.log(`runbook references checked against ${path.relative(ROOT, runbooks) || runbooks}`);
  } else if (flag('--offline')) {
    console.warn('WARNING: no checkout of openstack-vm-runbooks available, runbook references NOT checked');
  } else {
    fail([`no checkout of ${REPO} found and it could not be cloned. Pass --runbooks DIR, or --offline to skip the check.`]);
  }
  if (flag('--validate')) return console.log('content is valid');

  const only = opt('--only');
  const selected = only ? memos.filter((m) => m._slug === only || m.id === only) : memos;
  if (only && !selected.length) fail([`no memo with slug or id "${only}"`]);
  const scale = Number(opt('--scale') || 1);
  errors = await render(selected, scale);
  if (errors.length) fail(errors);

  for (const m of memos) fs.writeFileSync(path.join(ROOT, 'categories', m.category, `${m._slug}.md`), memoPage(m));
  for (const cat of Object.keys(CATEGORIES))
    if (memos.some((m) => m.category === cat)) fs.writeFileSync(path.join(ROOT, 'categories', cat, 'README.md'), categoryIndex(cat, memos));
  fs.writeFileSync(path.join(ROOT, 'LINKEDIN.md'), linkedinKit(memos));
  replaceBlock('README.md', 'catalog', catalog(memos));
  const readme = path.join(ROOT, 'README.md');
  if (fs.existsSync(readme))
    fs.writeFileSync(readme, fs.readFileSync(readme, 'utf8').replace(/badge\/memos-\d+-informational\.svg" alt="\d+ memos"/, `badge/memos-${memos.length}-informational.svg" alt="${memos.length} memos"`));
  replaceBlock('README.md', 'count', `**${memos.length} memos** across ${new Set(memos.map((m) => m.category)).size} categories.`);
  if (!only && scale === 1) await contactSheet(memos);
  errors = checkLocalLinks();
  if (errors.length) fail(errors);
  console.log('local links checked');
  console.log('done');
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
